#!/usr/bin/env python3
"""Build cf/cron/purge-worker.js: a single-file Cloudflare Worker (paste into the dashboard) that runs the retention purge daily.
Same code as cf/functions/api/_purge.js (inlined), so the API and the worker can never drift apart."""
import os, re
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lib = open(os.path.join(R, "cf/functions/api/_purge.js"), encoding="utf-8").read()
lib = re.sub(r"^export ", "", lib, flags=re.M)
out = """// GOV RADAR — daily retention purge (generated by tools/build_purge_worker.py from cf/functions/api/_purge.js; do not edit).
// Cloudflare dashboard: Workers & Pages → Create → Worker → paste this file → Settings → Bindings: D1 database, name GV_DB
// → Settings → Triggers → Cron: "17 18 * * *" (03:17 KST daily). No secrets, no public actions; results go to purge_runs.
""" + lib + """
export { purgeAll, purgeLogged };
export default {
  async scheduled(event, env, ctx) { ctx.waitUntil(purgeLogged(env.GV_DB, new Date(event.scheduledTime || Date.now()), "cron")); },
  async fetch() { return new Response("not found", { status: 404 }); }
};
"""
open(os.path.join(R, "cf/cron/purge-worker.js"), "w", encoding="utf-8").write(out); print("ok")
